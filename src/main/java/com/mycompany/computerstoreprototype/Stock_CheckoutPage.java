    private void sortByDirectionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_sortByDirectionActionPerformed
        Integer sortByIndex = sortByDirection.getSelectedIndex();
        Boolean ascending = false;

        //Logic for if its high to low / else
        if(sortByColumn.getSelectedIndex() == 1)
        {
            ascending = false;
        }
        else
        {
            ascending = true;
        }

        //Create Instances
        FileManagement fileManagement = new FileManagement();

        //Read file then quicksort
        String [][] arrayToSort = fileManagement.readFileToArray("items.txt",7);
        SortsAndSearches.quickSortInitialiser(arrayToSort,sortByIndex,ascending);

        //Reload Table
        DefaultTableModel browseItemsTable = (DefaultTableModel) itemsTable.getModel();
        browseItemsTable.setRowCount(0);
        for(int i=0;i<arrayToSort.length;i++)
        {
            browseItemsTable.addRow(arrayToSort[i]);
        }
    }//GEN-LAST:event_sortByDirectionActionPerformed

