    private void sortByColumnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_sortByColumnActionPerformed
        Integer sortByIndex = sortByDirection.getSelectedIndex();
        if(sortByIndex == 4)
        {
            sortByIndex += 1;
        }
        Boolean ascending = false;
        
        //Logic for if its high to low / else
        if(sortByColumn.getSelectedIndex() == 1) // variables were named wrong
        {
            ascending = false;
        }
        else
        {
            ascending = true;
        }
        
        //Create Instances
        FileManagement fileManagement = new FileManagement();
        
        //Read file then quicksort
        String[][] arrayToSort = fileManagement.readFileToArray("users.txt",7);
        SortsAndSearches.quickSortInitialiser(arrayToSort,sortByIndex,ascending);
       

        //Reload Table
        DefaultTableModel browseUsersTable = (DefaultTableModel) usersTable.getModel();
        browseUsersTable.setRowCount(0);
        for(int i=0;i<arrayToSort.length;i++)
        {
            browseUsersTable.addRow(arrayToSort[i]);
        }
    }//GEN-LAST:event_sortByColumnActionPerformed

