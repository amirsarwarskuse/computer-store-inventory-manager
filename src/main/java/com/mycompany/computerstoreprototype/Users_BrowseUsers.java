    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        
        
        try
        {
            // This section gets the ID ( Primary Key ) for the edit method
            Integer selectedRow = usersTable.getSelectedRow(); // gets selected row 
            Object value = usersTable.getValueAt(selectedRow, 0); // creates object of the element in column 0
            int idToEdit = Integer.parseInt(value.toString());
        
            //Declare variables
            String firstname = firstNameField.getText();
            String surname = surnameField.getText();
            String username = usernameField.getText();
            String password = passwordField.getText();
            String permissions;
            String status;
            Integer permissionsIndex = permissionsBox.getSelectedIndex();
            Integer statusIndex = statusBox.getSelectedIndex();
            Boolean errorMade = false;
            String errorMessage = "";
            Validator validate = new Validator();
            String usernameInTable = usersTable.getValueAt(selectedRow, 3).toString();
            
            
            if(permissionsIndex==0)
            {
                permissions = "Standard";
            }
            else
            {
                permissions = "Manager";
            }
           
            if(statusIndex==0)
            {
                status = "Enabled";
            }
            else
            {
                status = "Disabled";
            }

            // Presence checks 
            if (validate.presenceCheck(firstname)) 
            {
                errorMade = true;
                errorMessage += "First name is required.\n";
            }
            if (validate.presenceCheck(surname)) 
            {
                errorMade = true;
                errorMessage += "Surname is required.\n";
            }
            if (validate.presenceCheck(username)) 
            {
                errorMade = true;
                errorMessage += "Username is required.\n";
            }
            if (validate.presenceCheck(password)) 
            {
                errorMade = true;
                errorMessage += "Password is required.\n";
            }

            // Comma checks
            if (validate.commaBlock(firstname)) 
            {
                errorMade = true;
                errorMessage += "First name cannot contain commas.\n";
            }
            if (validate.commaBlock(surname)) 
            {
                errorMade = true;
                errorMessage += "Surname cannot contain commas.\n";
            }
            if (validate.commaBlock(username)) 
            {
                errorMade = true;
                errorMessage += "Username cannot contain commas.\n";
            }

            // Length Checks
            if (validate.lengthCheck(firstname, 100)) 
            {
                errorMade = true;
                errorMessage += "First name exceeds maximum length (100 characters).\n";
            }
            if (validate.lengthCheck(surname, 100)) 
            {
                errorMade = true;
                errorMessage += "Surname exceeds maximum length (100 characters).\n";
            }
            if (validate.lengthCheck(username, 30)) 
            {
                errorMade = true;
                errorMessage += "Username exceeds maximum length (30 characters).\n";
            }

            // Username Check
            if(!username.equals(usernameInTable))
            {
                if (validate.uniqueUsernameCheck(username)) 
                {
                    errorMade = true;
                    errorMessage += "Username is already taken. Please choose another one.\n";
                }
            }
            
            
            
            // Password Check if modify password is selected
            if(keepPassword.getSelectedIndex()==1)
            {
                
                if (validate.passwordCheck(password)) 
                {
                    errorMade = true;
                    errorMessage += "Invalid password. Password must be at least 8 characters long and contain at least one uppercase letter, one digit, and one special character.\n";
                }
            }
            
            if(errorMade==true)
            {
                JOptionPane.showMessageDialog(null,errorMessage,"Error",JOptionPane.ERROR_MESSAGE);
            }
            else
            {
                User user = new User(firstname,surname,username,password,permissions,status);
                user.editUsers(idToEdit,keepPassword.getSelectedIndex());
                JOptionPane.showMessageDialog(null,"The selected user was successfully updated","System Database",JOptionPane.INFORMATION_MESSAGE);

                //Reloads the table
                String[][] users = User.usersArray();
                DefaultTableModel browseItemsTable = (DefaultTableModel) usersTable.getModel();
                browseItemsTable.setRowCount(0);
                for(int i=0;i<users.length;i++)
                {
                    browseItemsTable.addRow(users[i]);
                }
                
                firstNameField.setText("Firstname");
                surnameField.setText("Surname");
                usernameField.setText("Username");
                passwordField.setText("Password");
            }
        }
        catch(Exception e)
        {
            JOptionPane.showMessageDialog(null,"A row must be selected to update","Error",JOptionPane.ERROR_MESSAGE);
        }
        
        
        
        
        
       
    }//GEN-LAST:event_updateButtonActionPerformed
    
