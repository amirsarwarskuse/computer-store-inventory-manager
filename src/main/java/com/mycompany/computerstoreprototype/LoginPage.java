    private void loginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginButtonActionPerformed
        //Initialise instances of classes
        PasswordsAndSecurity hashPassword = new PasswordsAndSecurity();
        
        //Get values from text fields and hash the password
        String username = usernameField.getText();
        String password = passwordField.getText();
        
        //Perform binary search for that username
        String[] foundUsername = SortsAndSearches.linearSearch("users.txt", username, 7,3);
        
        //If the username is found that the user entered, the primary key ( the salt ) is = to that related to the username
        if(foundUsername != null)
        {
            String primaryKey = foundUsername[0];
            String passwordHashed = hashPassword.hashLoop(primaryKey + password + "eHw8$n#5L@2aGt3Z"); //hash the users password 1000 times
            
            //if the hashed password thats saved matches the inputted hashed password proceed to the next step
            if(foundUsername[4].equals(passwordHashed))
            {
                //if the account is enabled allow them to login
                if(foundUsername[6].equals("Enabled"))
                {
                    //Display successfull login message
                    JOptionPane.showMessageDialog(null,"Authenticated Successfully!","Account Information",JOptionPane.INFORMATION_MESSAGE);
                    
                    //Open the home page
                    HomePage homePage = new HomePage();
                    homePage.setVisible(true);
                    this.dispose();
                    accountPermissions = foundUsername[5];
                }
                //if the account is disabled, display an error Message
                else
                {
                    JOptionPane.showMessageDialog(null,"This account is currently disabled","Account Information",JOptionPane.INFORMATION_MESSAGE);
                }
            }  
            //the password saved does not match what the user inputted so display an error message
            else
            {
                JOptionPane.showMessageDialog(null,"Incorrect username or password","Incorrect",JOptionPane.INFORMATION_MESSAGE); // do not say if its username or password specifically for security reasons
            }
        }
        else
        {
            JOptionPane.showMessageDialog(null,"Incorrect username or password","Incorrect",JOptionPane.INFORMATION_MESSAGE); // do not say if its username or password specifically for security reasons
        }  
    }//GEN-LAST:event_loginButtonActionPerformed

