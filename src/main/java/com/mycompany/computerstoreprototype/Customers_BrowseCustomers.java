    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        
        // This section gets the ID ( Primary Key ) for the edit method
        try
        {
            Integer selectedRow = customersTable.getSelectedRow(); // gets selected row 
            Object value = customersTable.getValueAt(selectedRow, 0); // creates object of the element in column 0
            int idToEdit = Integer.parseInt(value.toString()); 
            
            System.out.println(idToEdit);
        
            //Declare variables
            String firstname = firstNameField.getText();
            String surname = surnameField.getText();
            String email = emailField.getText();
            String phone = phoneField.getText();
            String dateCreated = dateCreatedField.getText();
            Boolean errorMade=false;
            String errorMessage = "";

            Validator validate = new Validator();

            // Presence Checks
            if(validate.presenceCheck(firstname))
            {
                errorMade = true; 
                errorMessage += "First name is required.\n";
            }
            if(validate.presenceCheck(surname))
            {
                errorMade = true; 
                errorMessage += "Surname is required.\n";
            }
            if(validate.presenceCheck(email))
            {
                errorMade = true; 
                errorMessage += "Email is required.\n";
            }
            if(validate.presenceCheck(phone))
            {
                errorMade = true; 
                errorMessage += "Phone number is required.\n";
            }
            if(validate.presenceCheck(dateCreated))
            {
                errorMade = true; 
                errorMessage += "Date created is required.\n";
            }

            // Comma checks
            if (validate.commaBlock(firstname)) 
            {
                errorMade = true; 
                errorMessage += "First name cannot contain commas.\n";
            }
            if (validate.commaBlock(surname)) 
            {
                errorMade = true; 
                errorMessage += "Surname cannot contain commas.\n";
            }
            if (validate.commaBlock(email)) 
            {
                errorMade = true; 
                errorMessage += "Email cannot contain commas.\n";
            }
            if (validate.commaBlock(phone)) 
            {
                errorMade = true; 
                errorMessage += "Phone number cannot contain commas.\n";
            }
            if (validate.commaBlock(dateCreated)) 
            {
                errorMade = true; 
                errorMessage += "Date created cannot contain commas.\n";
            }


            // Length Checks
            if(validate.lengthCheck(firstname, 60))
            {
                errorMade = true; 
                errorMessage += "First name exceeds maximum length of 60 characters.\n";
            }
            if(validate.lengthCheck(surname, 100))
            {
                errorMade = true; 
                errorMessage += "Surname exceeds maximum length of 100 characters.\n";
            }
            if(validate.lengthCheck(email, 255))
            {
                errorMade = true; 
                errorMessage += "Email exceeds maximum length of 255 characters.\n";
            }
            if(validate.lengthCheck(phone, 20))
            {
                errorMade = true; 
                errorMessage += "Phone number exceeds maximum length of 20 characters.\n";
            }
            if(validate.lengthCheck(dateCreated, 10))
            {
                errorMade = true; 
                errorMessage += "Date created exceeds maximum length of 10 characters.\n";
            }

            // Date Check
            if(validate.dateCheck(dateCreated))
            {
                errorMade = true; 
                errorMessage += "Invalid date format for Date created.\n";
            }

            // Phone Check
            if(validate.phoneCheck(phone))
            {
                errorMade = true; 
                errorMessage += "Invalid phone number format.\n";
            }

            // Email Check
            if(validate.emailCheck(email))
            {
                errorMade = true; 
                errorMessage += "Invalid email format.\n";
            }

            if(errorMade==true)
            {
                JOptionPane.showMessageDialog(null,errorMessage,"Error",JOptionPane.ERROR_MESSAGE);
            }
            else
            {
                Customer customer = new Customer(firstname,surname,email,phone,dateCreated);
                customer.editCustomers(idToEdit);
                JOptionPane.showMessageDialog(null,"The selected item was successfully updated.","System Database",JOptionPane.INFORMATION_MESSAGE);

                //Reloads the table
                String[][] customers = Customer.customersArray();
                DefaultTableModel browseItemsTable = (DefaultTableModel) customersTable.getModel();
                browseItemsTable.setRowCount(0);
                for(int i=0;i<customers.length;i++)
                {
                    browseItemsTable.addRow(customers[i]);
                }
            }
        }
        catch(Exception e)
        {
            JOptionPane.showMessageDialog(null,"A row must be selected to update","Error",JOptionPane.ERROR_MESSAGE);
        }
        
        
        
        
        
       
    }//GEN-LAST:event_updateButtonActionPerformed
    
