    private void registerButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerButtonActionPerformed
        //Declare variables and create instances
        String firstname = firstNameField.getText();
        String surname = surnameField.getText();
        String username = usernameField.getText();
        String password = passwordField.getText();
        Validator validate = new Validator();
        Boolean errorMade=false;
        String errorMessage = "";
        
        // Presence checks 
        if (validate.presenceCheck(firstname)) 
        {
            errorMade = true;
            errorMessage += "First name is required.\n";
        }
        if (validate.presenceCheck(surname)) 
        {
            errorMade = true;
            errorMessage += "Surname is required.\n";
        }
        if (validate.presenceCheck(username)) 
        {
            errorMade = true;
            errorMessage += "Username is required.\n";
        }
        if (validate.presenceCheck(password)) 
        {
            errorMade = true;
            errorMessage += "Password is required.\n";
        }

        // Comma checks
        if (validate.commaBlock(firstname)) 
        {
            errorMade = true;
            errorMessage += "First name cannot contain commas.\n";
        }
        if (validate.commaBlock(surname)) 
        {
            errorMade = true;
            errorMessage += "Surname cannot contain commas.\n";
        }
        if (validate.commaBlock(username)) 
        {
            errorMade = true;
            errorMessage += "Username cannot contain commas.\n";
        }

        // Length Checks
        if (validate.lengthCheck(firstname, 100)) 
        {
            errorMade = true;
            errorMessage += "First name exceeds maximum length (100 characters).\n";
        }
        if (validate.lengthCheck(surname, 100)) 
        {
            errorMade = true;
            errorMessage += "Surname exceeds maximum length (100 characters).\n";
        }
        if (validate.lengthCheck(username, 30)) 
        {
            errorMade = true;
            errorMessage += "Username exceeds maximum length (30 characters).\n";
        }

        // Username Check
        if (validate.uniqueUsernameCheck(username)) 
        {
            errorMade = true;
            errorMessage += "Username is already taken. Please choose another one.\n";
        }

        // Password Check
        if (validate.passwordCheck(password)) 
        {
            errorMade = true;
            errorMessage += "Invalid password. Password must be at least 8 characters long and contain at least one uppercase letter, one digit, and one special character.\n";
        }
        
        //Save
        if(errorMade==true)
        {
            JOptionPane.showMessageDialog(null,errorMessage,"Error",JOptionPane.ERROR_MESSAGE);
        }
        else
        {
            User user = new User(firstname,surname,username,password,"Standard","Disabled");
            user.saveUsers();
            JOptionPane.showMessageDialog(null,"Account has been registered successfully","Account Information",JOptionPane.INFORMATION_MESSAGE);
            LoginPage loginPage = new LoginPage();
            loginPage.setVisible(true);
            this.dispose();
        }
        
        
       
    }//GEN-LAST:event_registerButtonActionPerformed

