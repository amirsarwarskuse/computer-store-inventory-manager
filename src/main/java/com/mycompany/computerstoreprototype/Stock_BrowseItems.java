    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
        String searchValue = searchField.getText();
        FileManagement fileManagement = new FileManagement();

        // Read to Array and sort low to high
        String[][] arrayToSort = fileManagement.readFileToArray("items.txt", 7);
        String[][] sortedArray = SortsAndSearches.quickSortInitialiser(arrayToSort, 1, true);

        // Perform binary search
        String[] foundValue = SortsAndSearches.binarySearch(sortedArray, searchValue, 7,1);

        // Reload Table
        DefaultTableModel browseItemsTable = (DefaultTableModel) itemsTable.getModel();
        browseItemsTable.setRowCount(0); // Clear the table before adding new data

        // Check if the value is found before updating the table
        if (foundValue != null) 
        {
            Object[] rowData = new Object[7]; // Assuming 6 columns in your table
            for (int i = 0; i < 7; i++) 
            {
                rowData[i] = foundValue[i];
            }
            browseItemsTable.addRow(rowData); // Add the row to the table
        } 
        else 
        {
            // Display a message or handle the case when the value is not found
            JOptionPane.showMessageDialog(null,"No results found","Search Result",JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_searchButtonActionPerformed

