    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        
        // This section gets the ID ( Primary Key ) for the edit method
        //If the user has a standard account they will be unable to access this feature. accoutnPermissions is a global variable in login page that is assigned when logged in    
        if(LoginPage.accountPermissions.equals("Manager"))
        {
            try
            {
                Integer selectedRow = itemsTable.getSelectedRow(); // gets selected row 
                Object value = itemsTable.getValueAt(selectedRow, 0); // creates object of the element in column 0
                int idToEdit = Integer.parseInt(value.toString()); // adds one as edit method uses selected row which is 1 more than the ID

                // This section edits then reloads the table
                String itemName = itemNameField.getText();
                String brandName = brandField.getText();
                String itemType = itemTypeField.getText();
                String quantity = quantityField.getText();
                String price = priceField.getText();
                String discount = discountField.getText();
                Boolean errorMade = false;
                String errorMessage = "";
                Validator validate = new Validator();

                //presence check
                if(validate.presenceCheck(itemName))
                {
                    errorMade = true; 
                    errorMessage += "Item name field cannot be left empty\n";
                }
                if(validate.presenceCheck(brandName))
                {
                    errorMade = true; 
                    errorMessage += "Brand name field cannot be left empty\n";
                }
                if(validate.presenceCheck(itemType))
                {
                    errorMade = true; 
                    errorMessage += "Item type field cannot be left empty\n";
                }
                if(validate.presenceCheck(quantity))
                {
                    errorMade = true; 
                    errorMessage += "Quantity field cannot be left empty\n";
                }
                if(validate.presenceCheck(price))
                {
                    errorMade = true; 
                    errorMessage += "Price field cannot be left empty\n";
                }
                if(validate.presenceCheck(discount))
                {
                    errorMade = true; 
                    errorMessage += "Discount field cannot be left empty\n";
                }
                
                // Comma checks
                if (validate.commaBlock(itemName)) 
                {
                    errorMade = true;
                    errorMessage += "Item name cannot contain commas.\n";
                }
                if (validate.commaBlock(brandName)) 
                {
                    errorMade = true;
                    errorMessage += "Brand name cannot contain commas.\n";
                }
                if (validate.commaBlock(itemType)) 
                {
                    errorMade = true;
                    errorMessage += "Item type cannot contain commas.\n";
                }
                if (validate.commaBlock(quantity)) 
                {
                    errorMade = true;
                    errorMessage += "Quantity cannot contain commas.\n";
                }
                if (validate.commaBlock(price)) 
                {
                    errorMade = true;
                    errorMessage += "Price cannot contain commas.\n";
                }
                if (validate.commaBlock(discount)) 
                {
                    errorMade = true;
                    errorMessage += "Discount cannot contain commas.\n";
                }

                //length check on all fields
                if (validate.lengthCheck(itemName, 150)) 
                {
                    errorMade = true;
                    errorMessage += "Item name cannot exceed 150 characters\n";
                }
                if (validate.lengthCheck(brandName, 100)) 
                {
                    errorMade = true;
                    errorMessage += "Brand name cannot exceed 100 characters\n";
                }
                if (validate.lengthCheck(itemType, 50)) 
                {
                    errorMade = true;
                    errorMessage += "Item type cannot exceed 50 characters\n";
                }
                if (validate.lengthCheck(quantity, 6)) 
                {
                    errorMade = true;
                    errorMessage += "Quantity field cannot exceed 6 characters\n";
                }
                if (validate.lengthCheck(price, 10)) 
                {
                    errorMade = true;
                    errorMessage += "Price field cannot exceed 10 characters\n";
                }
                if (validate.lengthCheck(discount, 4)) 
                {
                    errorMade = true;
                    errorMessage += "Discount field cannot exceed 4 characters\n";
                }

                //type checks
                if(validate.intCheck(quantity))
                {
                    errorMade = true;
                    errorMessage += "Quantity field must consist of only integers\n";
                }
                if(validate.doubleCheck(discount))
                {
                    errorMade = true;
                    errorMessage += "Discount field must consist of only integers or decimals\n";
                }
                if(validate.doubleCheck(price))
                {
                    errorMade = true;
                    errorMessage += "Discount field must consist of only integers or decimals\n";
                }
                
                //price checker
                if(validate.priceCheck(price))
                {
                    errorMade = true;
                    errorMessage += "Price should have up to 2 decimal places.\n";
                }

                // Output error messages if errors are found, if not output save message and save

                if(errorMade==true)
                {
                    JOptionPane.showMessageDialog(null,errorMessage,"Error",JOptionPane.ERROR_MESSAGE);
                }
                else
                {
                    Item item = new Item(itemName,brandName,itemType,quantity,price,discount,idToEdit);
                    item.edit();
                    JOptionPane.showMessageDialog(null,"The selected item was successfully updated","System Database",JOptionPane.INFORMATION_MESSAGE);

                    //Reloads the table
                    String[][] items = Item.itemsArray();
                    DefaultTableModel browseItemsTable = (DefaultTableModel) itemsTable.getModel();
                    browseItemsTable.setRowCount(0);
                    for(int i=0;i<items.length;i++)
                    {
                        browseItemsTable.addRow(items[i]);
                    }
                    
                }
            }
            catch(Exception e)
            {
                JOptionPane.showMessageDialog(null,"A row must be selected to update","Error",JOptionPane.ERROR_MESSAGE);
            }
        }
        else
        {
            JOptionPane.showMessageDialog(null,"Insufficient permissions, please contact a manager for further information","Insufficient permissions",JOptionPane.ERROR_MESSAGE);
        }
        
        
       
    }//GEN-LAST:event_updateButtonActionPerformed
    
